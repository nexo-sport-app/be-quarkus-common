package it.nexoapp.common.context;

import it.nexoapp.common.constant.Language;
import jakarta.enterprise.context.RequestScoped;
import lombok.Data;

import java.io.Serial;
import java.io.Serializable;
import java.util.List;
import java.util.Map;

/**
 * Represents the context of an HTTP request during its lifecycle.
 * <p>
 * This class holds metadata and user-related information for the current request,
 * including headers, session identifiers, user details, and locale settings.
 * It provides a centralized way to access and manage request-specific data in a
 * thread-safe and scope-limited manner.
 * </p>
 * <p>
 * The {@code RequestScoped} annotation indicates that the lifecycle of this
 * class is bound to the scope of an HTTP request.
 */
@Data
@RequestScoped
public class RequestContext implements Serializable {

    @Serial
    private static final long serialVersionUID = -7978563029792028589L;

    // --
    // Request metadata
    // -----------------------------------------------------------------------------------------------------------------

    /**
     * Represents the HTTP headers associated with the current request.
     * <p>
     * This field contains a map of header names to their corresponding values.
     * Since HTTP headers can have multiple values for the same header name,
     * each entry maps a header name (String) to a list of values (List of Strings).
     * This is used for accessing request metadata such as content type, authorization
     * tokens, custom headers, and other HTTP protocol information.
     * <p>
     * Example: {@code {"Content-Type": ["application/json"], "Authorization": ["Bearer token123"]}}
     */
    private Map<String, List<String>> headers;

    /**
     * Represents the unique identifier for the user's session.
     * <p>
     * This field stores the session ID that tracks the user's session across
     * multiple requests. It is used for maintaining state, session management,
     * and associating multiple requests with the same user session. The session
     * ID is typically generated by the server and passed to the client via cookies
     * or other mechanisms.
     * <p>
     * Example: {@code "a1b2c3d4-e5f6-7890-g1h2-i3j4k5l6m7n8"}
     */
    private String sessionId;

    /**
     * Represents a unique identifier for tracking a specific API call or request.
     * <p>
     * This field is used for logging, debugging, and tracing requests across
     * distributed systems. It helps correlate log entries and monitor the flow
     * of a single request through various services and components.
     * <p>
     * Example: {@code "a1b2c3d4-e5f6-7890-g1h2-i3j4k5l6m7n8"}
     */
    private String callId;

    /**
     * Represents the IP address of the client making the request.
     * <p>
     * This field captures the originating IP address, which can be used for
     * security auditing, geolocation, rate limiting, and access control.
     * It may represent either an IPv4 or IPv6 address.
     * <p>
     * Example: {@code "192.168.1.100"} or {@code "2001:0db8:85a3:0000:0000:8a2e:0370:7334"}
     */
    private String ip;

    /**
     * Represents the preferred language for the current request.
     * <p>
     * This field indicates the language setting for localization and
     * internationalization purposes. It is used to determine which language
     * version of content, messages, and resources should be provided to the user.
     * <p>
     * Example: {@code Language.EN}, {@code Language.IT}
     */
    private Language language;

    // --
    // Basic user metadata
    // -----------------------------------------------------------------------------------------------------------------

    /**
     * Represents the unique identifier of the authenticated user.
     * <p>
     * This field contains the system-generated unique identifier that
     * distinguishes one user from another. It is typically used for
     * database lookups, authorization checks, and audit trails.
     * <p>
     * Example: {@code "123e4567-e89b-12d3-a456-426614174000"}
     */
    private String userId;
    /**
     * Represents the username of the authenticated user.
     * <p>
     * This field contains the human-readable identifier that the user
     * uses to log in to the system. It is distinct from the userId and
     * is often displayed in the user interface.
     * <p>
     * Example: {@code "john.doe"} or {@code "jdoe@example.com"}
     */
    private String username;

    /**
     * Represents the first name (given name) of the authenticated user.
     * <p>
     * This field stores the user's first name as provided during registration
     * or profile setup. It is commonly used for personalization and display
     * purposes in the user interface.
     * <p>
     * Example: {@code "John"}
     */
    private String firstName;

    /**
     * Represents the last name (surname/family name) of the authenticated user.
     * <p>
     * This field stores the user's last name as provided during registration
     * or profile setup. It is commonly used in combination with firstName
     * for full name display and formal communications.
     * <p>
     * Example: {@code "Doe"}
     */
    private String lastName;

    /**
     * Represents the email address of the authenticated user.
     * <p>
     * This field stores the user's primary email address, which is typically
     * used for communication, notifications, account recovery, and as an
     * alternative login identifier.
     * <p>
     * Example: {@code "john.doe@example.com"}
     */
    private String email;

}